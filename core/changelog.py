def notes(version: str) -> str:
    return "\n".join(f"• {line}" for line in CHANGELOG.get(version, []))


def _key(version: str) -> tuple:
    return tuple(int(x) if x.isdigit() else 0 for x in version.split("."))


def format_notes(changes: dict, low: tuple, top: tuple) -> str:
    """
    Список «что нового» для версий в промежутке (low, top].
    Если перешли на новое поколение (сменилась первая цифра), сначала — главное из X.0.0,
    потом исправления этого поколения, потом то, что вышло в прошлом поколении.
    Внутри блока — от новых версий к старым, повторы убираются.
    """
    versions = sorted((v for v in changes if low < _key(v) <= top), key=_key, reverse=True)
    seen: set = set()

    def block(vs) -> list:
        out = []
        for v in vs:
            for line in changes.get(v) or []:
                if isinstance(line, str) and line not in seen:
                    seen.add(line)
                    out.append(f"• {line}")
        return out

    head = (top[0], 0, 0)
    if low < head and any(_key(v) == head for v in versions):
        main = block([v for v in versions if _key(v) == head])
        fixes = block([v for v in versions if _key(v) > head])
        older = block([v for v in versions if _key(v)[0] < top[0]])
        parts = [f"Главное в {top[0]}.0:"] + main
        if fixes:
            parts += ["", f"Исправления и улучшения {top[0]}.x:"] + fixes
        if older:
            parts += ["", "Также с вашей версии:"] + older
        return "\n".join(parts)
    return "\n".join(block(versions))


def notes_since(previous: str | None, current: str) -> str:
    """Что нового с версии previous (не включая её) по current. previous=None — с начала текущего поколения (x.0.0)."""
    cur = _key(current)
    low = _key(previous) if previous else (cur[0], -1)
    return format_notes(CHANGELOG, low, cur)
