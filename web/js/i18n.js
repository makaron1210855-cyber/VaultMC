const I18N = {
  lang: 'ru',
  re: null,
  skip: '.no-tr, #logBox, .log, textarea, [contenteditable], .inst-card .title, .world .title, .server .title, .shot, .nametag'
};

function i18nRegex() {
  if (I18N.re) return I18N.re;
  const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const keys = Object.keys(I18N_EN).sort((a, b) => b.length - a.length).map(esc);
  I18N.re = new RegExp(`(?<![А-Яа-яЁё])(?:${keys.join('|')})(?![А-Яа-яЁё])`, 'g');
  return I18N.re;
}

function trText(text) {
  if (!text || !/[А-Яа-яЁё]/.test(text)) return text;
  return text.replace(i18nRegex(), (m) => I18N_EN[m] ?? m);
}
const tr = (text) => (I18N.lang === 'en' ? trText(text) : text);

function trNode(root) {
  if (I18N.lang !== 'en' || !root) return;
  if (root.nodeType === 3) {
    if (!root.parentElement?.closest(I18N.skip)) {
      const t = trText(root.nodeValue);
      if (t !== root.nodeValue) root.nodeValue = t;
    }
    return;
  }
  if (root.nodeType !== 1 || root.closest?.(I18N.skip)) return;
  for (const attr of ['placeholder', 'title', 'data-tip', 'aria-label']) {
    const v = root.getAttribute?.(attr);
    if (v) { const t = trText(v); if (t !== v) root.setAttribute(attr, t); }
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
    acceptNode: (n) => (n.nodeType === 1 && n.matches(I18N.skip) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  let n = walker.nextNode();
  while (n) {
    if (n.nodeType === 3) {
      const t = trText(n.nodeValue);
      if (t !== n.nodeValue) n.nodeValue = t;
    } else {
      for (const attr of ['placeholder', 'title', 'data-tip', 'aria-label']) {
        const v = n.getAttribute(attr);
        if (v) { const t = trText(v); if (t !== v) n.setAttribute(attr, t); }
      }
    }
    n = walker.nextNode();
  }
}

const I18N_OBS = new MutationObserver((list) => {
  for (const m of list) {
    if (m.type === 'characterData') trNode(m.target);
    else if (m.type === 'attributes') trNode(m.target);
    else m.addedNodes.forEach(trNode);
  }
});

function setLanguage(lang) {
  I18N.lang = lang === 'en' ? 'en' : 'ru';
  document.documentElement.lang = I18N.lang;
  I18N_OBS.disconnect();
  if (I18N.lang === 'en') {
    trNode(document.body);
    document.title = trText(document.title);
    I18N_OBS.observe(document.body, { childList: true, subtree: true, characterData: true,
      attributes: true, attributeFilter: ['placeholder', 'title', 'data-tip', 'aria-label'] });
  }
}
